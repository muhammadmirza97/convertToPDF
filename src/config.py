def get_inactivity_timeout_ms() -> int:
    """Return the configured idle timeout, falling back safely to 30 minutes."""
    raw_value = os.environ.get(INACTIVITY_TIMEOUT_ENV)
    if raw_value is None:
        return DEFAULT_INACTIVITY_TIMEOUT_SECONDS * 1000
    try:
        seconds = int(raw_value)
    except ValueError:
        return DEFAULT_INACTIVITY_TIMEOUT_SECONDS * 1000
    if seconds < 1:
        return DEFAULT_INACTIVITY_TIMEOUT_SECONDS * 1000
    return seconds * 1000

